"""Rebuild homepage WOFF2 subsets when changing its fonts or frequently used characters.

Use Python 3.9+ with fonttools==4.60.2 and brotli==1.2.1, then run
python scripts/subset-home-fonts.py. Normal site builds use the checked-in files.
"""

from io import BytesIO
from itertools import groupby
from pathlib import Path
import sys

from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "public/fonts"
OUTPUT = ROOT / "src/assets/home-fonts"

# Quicksand reserves its name for the original. The subset and its named
# weight instances use "Home Sans"; the original keeps its embedded names.
FACES = [
    ("quicksand-latin", "home-sans", "Home Sans", "normal", "300 700",
     "".join(chr(n) for n in range(32, 127)) + "·•©…"),
    ("cormorant-garamond-latin", "home-serif", "Cormorant Garamond", "normal", "400 700",
     "0123456789MTWFS "),
    ("cormorant-garamond-italic-latin", "home-serif-italic", "Cormorant Garamond", "italic", "400 500",
     "iqwqi's world • cs learner • code lover • embedded explorer • dreamer • creator • Popular tags Latest post"),
]


def unicode_ranges(codepoints):
    groups = groupby(enumerate(sorted(codepoints)), key=lambda pair: pair[1] - pair[0])
    result = []
    for _, group in groups:
        values = [value for _, value in group]
        result.append(f"U+{values[0]:X}" + (f"-{values[-1]:X}" if len(values) > 1 else ""))
    return ", ".join(result)


def face_rule(family, style, weights, url, coverage):
    return f"""@font-face {{
  font-family: '{family}';
  font-style: {style};
  font-weight: {weights};
  font-display: swap;
  src: url('{url}') format('woff2');
  unicode-range: {unicode_ranges(coverage)};
}}"""


def check_glyphs(original, smaller, expected):
    before = original.getBestCmap()
    after = smaller.getBestCmap()
    assert set(after) == expected
    assert original["fvar"].axes[0].axisTag == smaller["fvar"].axes[0].axisTag == "wght"
    for weight in (300, 400, 500, 600, 700):
        reference = original.getGlyphSet(location={"wght": weight})
        actual = smaller.getGlyphSet(location={"wght": weight})
        for cp, name in after.items():
            old_shape = DecomposingRecordingPen(reference)
            new_shape = DecomposingRecordingPen(actual)
            reference[before[cp]].draw(old_shape)
            actual[name].draw(new_shape)
            assert old_shape.value == new_shape.value and reference[before[cp]].width == actual[name].width, (cp, weight)


def generate(check_only):
    css = ["/* Generated by scripts/subset-home-fonts.py from the local fonts. */"]
    outputs = {}
    for original_name, filename, family, style, weights, characters in FACES:
        path = SOURCES / f"{original_name}.woff2"
        original = TTFont(path)
        font = TTFont(path, recalcTimestamp=False)
        options = subset.Options()
        options.layout_features = ["*"]  # keep kerning, ligatures and other shaping features
        options.name_IDs = ["*"]
        options.name_languages = ["*"]
        options.name_legacy = True
        subsetter = subset.Subsetter(options)
        subsetter.populate(text=characters)
        subsetter.subset(font)
        if filename == "home-sans":
            for name in font["name"].names:
                if name.nameID in (0, 13, 14):
                    continue  # copyright and license
                value = name.toUnicode().replace("Quicksand", "HomeSans")
                if name.nameID in (1, 4, 16):
                    value = value.replace("HomeSans", "Home Sans")
                name.string = value.encode(name.getEncoding())

        covered = set(map(ord, characters))
        check_glyphs(original, font, covered)
        other = set(original.getBestCmap()) - covered
        css.append(face_rule(family, style, weights, f"./{filename}.woff2?no-inline", covered))
        css.append(face_rule(family, style, weights, f"/fonts/{path.name}", other))
        data = BytesIO()
        font.save(data)
        outputs[OUTPUT / f"{filename}.woff2"] = data.getvalue()
    outputs[OUTPUT / "faces.css"] = ("\n\n".join(css) + "\n").encode()
    for path, content in outputs.items():
        if check_only:
            if path.read_bytes() != content:
                raise SystemExit(f"{path.name} needs to be regenerated")
        else:
            path.write_bytes(content)


if __name__ == "__main__":
    if sys.argv[1:] not in ([], ["--check"]):
        raise SystemExit("usage: subset-home-fonts.py [--check]")
    generate(check_only=bool(sys.argv[1:]))
